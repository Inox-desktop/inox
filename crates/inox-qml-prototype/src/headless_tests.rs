//! Headless unit tests proving the cxx-qt 0.10 bridge compiles, links and runs
//! entirely without a Wayland compositor (ADR 0033/0035 evidence).
//!
//! Qt runs on the offscreen platform, so no display or compositor is needed.
//! Two concerns are covered:
//!
//!   * `bridge_rust_struct_defaults`: the Rust backing struct gadget the QObject
//!     owns is constructible and its fields plumb through `#[qproperty]`.
//!   * `qml_engine_loads_module_offscreen`: a `QQmlApplicationEngine` can be
//!     created and pointed at the bundled `com.inox.prototype.qml` module URL on
//!     the offscreen platform without crashing, proving the bridge-generated
//!     QML type registration survives a build+tell without a compositor.
//!
//! These live as `#[cfg(test)]` unit tests inside the binary (rather than an
//! integration test in a separate crate) because — as with the binary itself —
//! cxx-qt 0.10 requires the target that exercises the bridge to also be the
//! target that declares it, so that the generated `cxx_qt_init_*` definitions
//! are referenced and not dropped by the linker (KDAB issue #770).
//!
//! cxx-qt deliberately refrains from exposing a public Rust-side factory for a
//! bare `#[qobject]` (only `#[qml_element]` QML registration and the `createRs`
//! Rust-struct constructor are generated), so driving the *C++* QObject
//! directly from pure Rust is out of scope here; the real end-to-end bridge
//! (QML → Rust) is exercised on a real Qt platform in CI.
//!
//! Run with:
//!
//! ```sh
//! QT_QPA_PLATFORM=offscreen cargo test -p inox-qml-prototype --bin inox-qml-prototype
//! ```

use cxx_qt_lib::{QGuiApplication, QQmlApplicationEngine, QUrl};

/// The `#[qobject]`'s Rust backing struct must be `Default`-constructible
/// (cxx-qt's default constructor path) and its `#[qproperty]` fields must read
/// back from the Rust side — the state cxx-qt keeps in Rust and surfaces to QML
/// through the generated `Q_PROPERTY` glue.
#[test]
fn bridge_rust_struct_defaults() {
    // cxx-qt 0.10 exposes no public Rust-side factory for a bare `#[qobject]`;
    // the `#[qproperty]` accessors live on the generated *C++* QObject, which
    // QML instantiates. Constructing the Rust backing struct here still
    // validates the Default-based default constructor path that the bridge
    // relies on, and that the property defaults are sane.
    let obj = super::cxxqt_object::MyObjectRust::default();
    assert_eq!(obj.number, 0, "number must default to 0");
}

/// A `QGuiApplication` + `QQmlApplicationEngine` can be constructed and pointed
/// at the bundled `main.qml` on the offscreen platform without a compositor,
/// and the QML module loads without aborting.
#[test]
fn qml_engine_loads_module_offscreen() {
    // Safety: must be set before any QGuiApplication/QCoreApplication exists or
    // the offscreen platform cannot be selected. Test-only environment write.
    unsafe {
        std::env::set_var("QT_QPA_PLATFORM", "offscreen");
    }

    let mut app = QGuiApplication::new();
    assert!(
        app.as_mut().is_some(),
        "QGuiApplication must construct on the offscreen platform"
    );

    let mut engine = QQmlApplicationEngine::new();
    assert!(
        engine.as_mut().is_some(),
        "QQmlApplicationEngine must construct on the offscreen platform"
    );

    // Loading `main.qml` instantiates the `com.inox.prototype.qml` module,
    // whose registration of the Rust-backed `MyObject` type is generated by
    // cxx-qt's build script. The URL comes from the binary itself so this test
    // cannot drift from what `main` loads.
    //
    // `QQmlApplicationEngine::load` is asynchronous and cxx-qt-lib 0.10 exposes
    // no Rust-side `rootObjects()`, so this test cannot observe a failed load
    // from here — it only proves the engine constructs and `load` does not
    // abort. That a load actually *succeeds* is asserted on a real Qt platform
    // by the D02 waydriver host test
    // (`crates/inox-integration/tests/waydriver_host.rs`), which requires the
    // composited Qt surface to appear in the compositor's frame. Do not read
    // this test as evidence that the QML tree loaded.
    let url = QUrl::from(super::MAIN_QML_URL);
    if let Some(engine) = engine.as_mut() {
        engine.load(&url);
    }

    // Keep the engine alive until after the event pump so Qt tears down
    // cleanly (drop order: engine before app).
    drop(engine);
    drop(app);
}
